<p>A post-meal walk isn't a free pass to eat anything you like, and it isn't a substitute for medication, sleep, or weight management for those whose doctors have advised those. It's one well-evidenced piece of the bigger picture, with the unusual virtue of being free, gentle, and immediately doable.</p>

