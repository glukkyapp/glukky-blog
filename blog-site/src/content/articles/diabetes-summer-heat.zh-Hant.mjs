<h2 id="why-heat-affects-blood-sugar">為什麼天熱會影響血糖？</h2>

<p>天氣熱的時候，身體會流更多汗，水份流失得比較快，如果沒有及時補充水份，血糖反而會偏高。<sup><a href="#src-1">1</a></sup>另外，高溫也會讓身體對藥物或胰島素的反應變得不太一樣，有時比平時容易出現低血糖。</p>

<h2 id="heading-out">出門在外要注意什麼？</h2>

<ul>
  <li><strong>多喝水</strong>，即使不覺得渴，也要記得定時喝一點。</li>
  <li>盡量避免<strong>中午最熱的時段</strong>外出，早上或黃昏比較舒服。</li>
